from itertools import permutations

# =========================================================
# T3: TRIAD CLASSIFICATION
# =========================================================
EDGE_BITS = [(0, 1), (0, 2), (1, 0), (1, 2), (2, 0), (2, 1)]
CODE_TO_CLASS = {
    3: 1, 6: 2, 7: 3, 10: 4, 11: 5, 15: 6, 21: 7,
    23: 8, 25: 9, 27: 10, 30: 11, 31: 12, 63: 13,
}

def _config_code(order, edges):
    code = 0
    for bit, (i, j) in enumerate(EDGE_BITS):
        if (order[i], order[j]) in edges:
            code |= (1 << bit)
    return code

def triad_class(a, b, c, edges):
    nodes = (a, b, c)
    codes = []
    for order in permutations(nodes):
        codes.append(_config_code(order, edges))
    canonical = min(codes)
    return CODE_TO_CLASS.get(canonical, 0)

# =========================================================
# T2: INDUCED SUBGRAPHS
# =========================================================
def build_induced_subgraph(edge_list, members):
    """Returns only the edges where BOTH endpoints are in the department."""
    subgraph_edges = set()
    for u, v in edge_list:
        if u in members and v in members:
            subgraph_edges.add((u, v))
    return subgraph_edges

